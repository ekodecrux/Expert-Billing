export function getOtherSectorDefaultCategories(activeSector: BusinessSector): Set<string> {
  const activeSet = new Set(
    (BUSINESS_SECTORS_CATALOG[activeSector]?.defaultCategories || []).map((c) => c.toLowerCase())
  );
  const others = new Set<string>();
  (Object.keys(BUSINESS_SECTORS_CATALOG) as BusinessSector[]).forEach((secKey) => {
    if (secKey === activeSector) return;
    BUSINESS_SECTORS_CATALOG[secKey].defaultCategories.forEach((cat) => {
      if (!activeSet.has(cat.toLowerCase())) {
        others.add(cat.toLowerCase());
      }
    });
  });
  return others;
}

const SECTOR_SAMPLE_SKU_PREFIX: Record<BusinessSector, string[]> = {
  RESTAURANT: ["RES-"],
  PHARMACY: ["RX-", "MED-"],
  RETAIL: ["APP-", "FTW-", "ACC-"],
  FASHION_GARMENT: ["FSH-"],
  SERVICES: ["SRV-"],
  PG_HOSTEL: ["PG-"],
  SUPERMARKET: ["SKU-"],
};

export function isProductMatchingSector(product: Product, activeSector: BusinessSector): boolean {
  const activeCatalog = BUSINESS_SECTORS_CATALOG[activeSector] || BUSINESS_SECTORS_CATALOG.SUPERMARKET;
  const activeCategories = new Set(activeCatalog.defaultCategories.map((c) => c.toLowerCase()));
  if (product.category && activeCategories.has(product.category.toLowerCase())) {
    return true;
  }

  const skuUpper = (product.sku || "").toUpperCase();
  const activePrefixes = SECTOR_SAMPLE_SKU_PREFIX[activeSector] || [];
  if (activePrefixes.some((pfx) => skuUpper.startsWith(pfx))) {
    return true;
  }

  // If product doesn't belong to any other sector's seeded categories or SKU prefixes, keep custom user products visible
  const otherCats = getOtherSectorDefaultCategories(activeSector);
  const belongsToOtherSectorCat = Boolean(product.category && otherCats.has(product.category.toLowerCase()));
  const belongsToOtherSectorSku = (Object.keys(SECTOR_SAMPLE_SKU_PREFIX) as BusinessSector[])
    .filter((s) => s !== activeSector)
    .some((s) => SECTOR_SAMPLE_SKU_PREFIX[s].some((pfx) => skuUpper.startsWith(pfx)));

  return !belongsToOtherSectorCat && !belongsToOtherSectorSku;
}

