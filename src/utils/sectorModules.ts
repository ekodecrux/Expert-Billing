export function buildSectorConfig(
  sector: BusinessSector,
  overrides?: Record<string, boolean>
): TenantSectorConfig {
  const catalog = BUSINESS_SECTORS_CATALOG[sector] || BUSINESS_SECTORS_CATALOG.SUPERMARKET;
  const mergedModules: TenantSectorConfig["enabledModules"] = { ...catalog.defaultModules };

  if (overrides) {
    (Object.keys(catalog.defaultModules) as SectorModuleKey[]).forEach((key) => {
      if (typeof overrides[key] === "boolean") {
        mergedModules[key] = overrides[key];
      }
    });
  }

  return {
    sector,
    sectorName: catalog.label,
    enabledModules: mergedModules,
    posMode: catalog.posMode,
    defaultCategories: [...catalog.defaultCategories],
    unitPresets: [...catalog.unitPresets],
    quickActions: [...catalog.quickActions],
  };
}

